#!/usr/bin/env python3
"""Hoenn & Seek 2.1 (parts 18-20): gym leaders' weekends.

A leader you've beaten takes Saturdays and Sundays off (2.1-plan section 6): their
gym object and follower are hidden, the gym guide says where they went, and they
stand at a weekend spot with a line and their usual rematch (HnS's Fighting Dojo
rematch, once that's open). Their Dojo copy takes the weekend off too.

Reads data/hoenn/leader_weekends.json (its comment explains the fields) and writes:
  - include/constants/hoenn_weekends.h: three flags per leader, from the leader's
    slot in lane B's 2.1 block (HOENN_21_WEEKEND_FLAGS):
      FLAG_HOENN_WEEKEND_GYM_<KEY>   the gym object's flag (and its follower's):
                                     set while the story hides the leader or they're away;
      FLAG_HOENN_WEEKEND_SPOT_<KEY>  the weekend spot object's flag: clear only while away;
      FLAG_HOENN_WEEKEND_DOJO_<KEY>  the Dojo copy's flag: HnS's FLAG_HIDE_DOJO_* or away.
    HoennUpdateLeaderWeekends() (src/hoenn_2_1_lane_b.c) sets all three on every
    map load, from the table below.
  - src/data/hoenn_leader_weekends.h: that table.
  - data/scripts/hoenn_weekends.inc: each spot's script, each gym guide's wrapper
    (the weekend line, else the guide's own script) and the texts (word-wrapped here).
  - map.json edits: the gym leader's flag, the guide's script, the Dojo objects'
    flags (every object with the leader's FLAG_HIDE_DOJO_*, so their Pokémon too),
    and the spot object (found by its script name, so re-runs replace it).
The leaders' followers (gym and spot) come from gen_hoenn_followers.py, which copies
the trainer's flag: run this first. Idempotent; regen_all.sh runs it in that order.
"""
import json, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_hoenn_hints import wrap  # same message-box wrapping as the hint lines

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
P = lambda *a: os.path.join(ROOT, *a)
DOJO = "SaffronCity_FightingDojoVIP_hns"
SLOTS = 24  # flag block: 3 flags per leader (constants/hoenn_events_2_1.h)
FACING = {"UP", "DOWN", "LEFT", "RIGHT"}
HEADER = "@ Generated by tools/hoenn/gen_hoenn_weekends.py from data/hoenn/leader_weekends.json. Don't edit.\n"


def load(name):
    return json.load(open(P("data/maps", name, "map.json")))


def save(name, m):
    with open(P("data/maps", name, "map.json"), "w") as fh:
        json.dump(m, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


def spot_script(key):
    return "HoennSeek_EventScript_Weekend_" + key


def guide_script(key):
    return "HoennSeek_EventScript_WeekendGuide_" + key


def dojo_script(key):
    return "SaffronCity_FightingDojoVIP_EventScript_" + key.capitalize()


def main():
    leaders = json.load(open(P("data/hoenn/leader_weekends.json")))["leaders"]
    keys, slots = set(), set()
    for l in leaders:
        if l["key"] in keys or l["slot"] in slots or not 0 <= l["slot"] < SLOTS:
            sys.exit("leader_weekends.json: duplicate or out-of-range key/slot at %s" % l["key"])
        keys.add(l["key"]); slots.add(l["slot"])
        if l["spot"]["facing"] not in FACING:
            sys.exit("%s: facing must be one of %s" % (l["key"], sorted(FACING)))

    # ---- constants ------------------------------------------------------------
    h = ["// Generated by tools/hoenn/gen_hoenn_weekends.py from data/hoenn/leader_weekends.json. Don't edit.",
         "// Three flags per leader (gym, spot, dojo); see the generator's header.",
         "#ifndef GUARD_CONSTANTS_HOENN_WEEKENDS_H", "#define GUARD_CONSTANTS_HOENN_WEEKENDS_H", ""]
    for l in sorted(leaders, key=lambda l: l["slot"]):
        b = "(HOENN_21_WEEKEND_FLAGS + %d)" % (l["slot"] * 3)
        for i, kind in enumerate(("GYM", "SPOT", "DOJO")):
            h.append("#define FLAG_HOENN_WEEKEND_%s_%s %s" % (kind, l["key"], b if i == 0 else
                     "(HOENN_21_WEEKEND_FLAGS + %d)" % (l["slot"] * 3 + i)))
    h += ["", "#define HOENN_WEEKEND_LEADER_COUNT %d" % len(leaders), "", "#endif // GUARD_CONSTANTS_HOENN_WEEKENDS_H", ""]
    open(P("include/constants/hoenn_weekends.h"), "w").write("\n".join(h))

    # ---- C table ----------------------------------------------------------------
    c = ["// Generated by tools/hoenn/gen_hoenn_weekends.py from data/hoenn/leader_weekends.json. Don't edit.",
         "// Read by HoennUpdateLeaderWeekends (src/hoenn_2_1_lane_b.c).",
         "static const struct HoennLeaderWeekend sLeaderWeekends[] = {"]
    for l in leaders:
        c.append("    { // %s" % l["key"])
        c.append("        .beaten = %s, .storyHide = %s, .dojoHide = %s," % (l["beaten"], l["story_flag"], l["dojo"] or "0"))
        c.append("        .gymFlag = FLAG_HOENN_WEEKEND_GYM_%s, .spotFlag = FLAG_HOENN_WEEKEND_SPOT_%s, .dojoFlag = %s," % (
            l["key"], l["key"], ("FLAG_HOENN_WEEKEND_DOJO_" + l["key"]) if l["dojo"] else "0"))
        c.append("    },")
    c += ["};", ""]
    open(P("src/data/hoenn_leader_weekends.h"), "w").write("\n".join(c))

    # ---- scripts ------------------------------------------------------------------
    s = [HEADER, "@ Hoenn & Seek 2.1 (parts 18-20): gym leaders' weekend spots and gym guides.", ""]
    for l in leaders:
        k = l["key"]
        s += ["%s::" % spot_script(k), "\tlock", "\tfaceplayer",
              "\tmsgbox HoennSeek_Text_Weekend_%s, MSGBOX_DEFAULT" % k]
        if l["dojo"]:  # HnS's Dojo rematch, once it's open (it asks, battles and gives BP)
            s.append("\tgoto_if_unset %s, %s" % (l["dojo"], dojo_script(k)))
        s += ["\tclosemessage", "\trelease", "\tend", ""]
        if l["guide"]:
            s += ["%s::" % guide_script(k),
                  "\tgoto_if_set FLAG_HOENN_WEEKEND_SPOT_%s, %s" % (k, l["guide"]),
                  "\tmsgbox HoennSeek_Text_WeekendGuide_%s, MSGBOX_NPC" % k, "\tend", ""]
    for l in leaders:
        k = l["key"]
        s += ["HoennSeek_Text_Weekend_%s:" % k, '\t.string "%s$"' % wrap(l["line"]), ""]
        if l["guide"]:
            s += ["HoennSeek_Text_WeekendGuide_%s:" % k, '\t.string "%s$"' % wrap(l["guide_line"]), ""]
    open(P("data/scripts/hoenn_weekends.inc"), "w").write("\n".join(s))

    # ---- map.json edits -------------------------------------------------------------
    dojo = load(DOJO)
    for l in leaders:
        k = l["key"]
        gym_flag = "FLAG_HOENN_WEEKEND_GYM_" + k
        g = load(l["gym"])
        found = [o for o in g["object_events"] if o["graphics_id"] == l["trainer"]]
        if len(found) != 1:
            sys.exit("%s: expected one %s, found %d" % (l["gym"], l["trainer"], len(found)))
        if found[0]["flag"] not in (l["story_flag"], gym_flag):
            sys.exit("%s: %s has flag %s, expected %s (story_flag) or %s" % (
                l["gym"], l["trainer"], found[0]["flag"], l["story_flag"], gym_flag))
        found[0]["flag"] = gym_flag
        if l["guide"]:
            guides = [o for o in g["object_events"] if o["script"] in (l["guide"], guide_script(k))]
            if len(guides) != 1:
                sys.exit("%s: expected one guide running %s, found %d" % (l["gym"], l["guide"], len(guides)))
            guides[0]["script"] = guide_script(k)
        save(l["gym"], g)

        if l["dojo"]:
            dojo_flag = "FLAG_HOENN_WEEKEND_DOJO_" + k
            hits = [o for o in dojo["object_events"] if o["flag"] in (l["dojo"], dojo_flag)]
            if not hits:
                sys.exit("%s: no object with %s" % (DOJO, l["dojo"]))
            for o in hits:
                o["flag"] = dojo_flag

        sp = l["spot"]
        m = load(sp["map"])
        objs = [o for o in m["object_events"] if o["script"] != spot_script(k)]
        if any(o["graphics_id"] == l["trainer"] for o in objs):
            sys.exit("%s: already has a %s (the follower generator needs it unique)" % (sp["map"], l["trainer"]))
        if any(int(o["x"]) == sp["x"] and int(o["y"]) == sp["y"] for o in objs):
            sys.exit("%s: an object already stands at %d,%d" % (sp["map"], sp["x"], sp["y"]))
        objs.append({
            "graphics_id": l["trainer"], "x": sp["x"], "y": sp["y"], "elevation": sp["elevation"],
            "movement_type": "MOVEMENT_TYPE_FACE_" + sp["facing"],
            "movement_range_x": 0, "movement_range_y": 0,
            "trainer_type": "TRAINER_TYPE_NONE", "trainer_sight_or_berry_tree_id": "0",
            "script": spot_script(k), "flag": "FLAG_HOENN_WEEKEND_SPOT_" + k,
        })
        if len(objs) > 64:  # OBJECT_EVENT_TEMPLATES_COUNT (the follower adds one more)
            sys.exit("%s: more than 64 objects" % sp["map"])
        m["object_events"] = objs
        save(sp["map"], m)
        print("%-8s gym %-24s spot %s (%d,%d)" % (k, l["gym"], sp["map"], sp["x"], sp["y"]))
    save(DOJO, dojo)


if __name__ == "__main__":
    main()

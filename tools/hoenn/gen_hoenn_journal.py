#!/usr/bin/env python3
"""Hoenn & Seek 2.1-05: the SEEKER'S JOURNAL's event table.

Reads data/hoenn/journal.json (its comment explains the format) and
data/hoenn/npc_hints.json (for hint line and rumor positions), and writes:
  - include/constants/hoenn_journal.h: FLAG_HOENN_HEARD_<KEY>, one per entry,
    from 2.1's generated journal block (HOENN_21_JOURNAL_FLAGS);
  - src/data/hoenn_journal.h: the entry table and the call -> heard-flag table
    (read by src/hoenn_journal.c);
  - src/data/hoenn_journal_hints.h: the heard flag of every hint line, in
    npc_hints.json's order (0 = none; read by src/hoenn_hints.c, which checks
    the size against its own table at build time);
  - data/scripts/hoenn_journal_texts.inc: every text, word-wrapped like the
    hint texts (included from data/scripts/hoenn_2_1_lane_a.inc).

Heard flags are saved, so an entry keeps its number for good:
data/hoenn/journal_flags.json (committed) maps each key to its number, new
keys get the next free one, and a number is never given to another key, even
after its entry is deleted. Run it after gen_hoenn_hints.py (regen_all.sh
does), and again whenever either JSON changes. Deterministic.
"""
import json, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_hoenn_hints import wrap, conds_c, P  # same text width and condition syntax

FLAG_BLOCK = 0x80       # heard flags: HOENN_21_JOURNAL_FLAGS + 0x00..0x7F (constants/hoenn_events_2_1.h)
NAME_MAX = 18           # list names: the menu's width (checked in the emulator)
KEY_RE = re.compile(r"^[A-Z0-9_]+$")


DAYS = ["SUN", "MON", "TUE", "WED", "THU", "FRI", "SAT"]
TIMES = {"morning": (1, "in the morning"), "day": (2, "by day"), "evening": (4, "in the evening"),
         "night": (8, "at night")}
TIDES = {"low": (1, "at low tide"), "high": (2, "at high tide")}


def when_text(w):
    """The Today page's line for an entry: its own text, or one built from the times."""
    if "text" in w:
        return w["text"]
    parts = []
    if "hour" in w:
        parts.append("at noon" if w["hour"] == 12 else "at %d o'clock" % w["hour"])
    if w.get("times"):
        ts = [TIMES[t][1] for t in w["times"]]
        parts.append(ts[0] if len(ts) == 1 else ", ".join(ts[:-1]) + " or " + ts[-1])
    if "tide" in w:
        parts.append(TIDES[w["tide"]][1])
    if w.get("weather"):
        parts.insert(0, "the weather has turned there")
    if not parts:
        parts = ["all day"]
    t = ", ".join(parts)
    return t[0].upper() + t[1:] + "."


def when_c(w, name, texts):
    """C initializer for an entry's Today-page rule (src/hoenn_journal.c), or NULL."""
    if not w:
        return "NULL"
    days = 0
    for d in w.get("days", []):
        days |= 1 << DAYS.index(d)
    times = 0
    for t in w.get("times", []):
        times |= TIMES[t][0]
    maps = []
    for m in w.get("weather", []):
        maps.append(json.load(open(P("data/maps", m, "map.json")))["id"])
    label = "HoennSeek_Text_Journal%sWhen" % name
    texts.append((label, wrap(when_text(w))))
    return "&(const struct HoennJournalWhen){ %s, %d, 0x%02X, 0x%X, %d, %d, %s, %s }" % (
        "(const u16[]){%s}" % ", ".join(maps) if maps else "NULL", len(maps), days, times,
        w.get("hour", 0xFF), TIDES[w["tide"]][0] if "tide" in w else 0, "TRUE" if w.get("repeat") else "FALSE", label)


def main():
    cfg = json.load(open(P("data/hoenn/journal.json")))
    hints = json.load(open(P("data/hoenn/npc_hints.json")))
    pages = [p.lower() for p in cfg["pages"]]
    lock_path = P("data/hoenn/journal_flags.json")
    lock = json.load(open(lock_path)) if os.path.exists(lock_path) else {"_comment": "", "flags": {}}
    lock["_comment"] = ("Generated by tools/hoenn/gen_hoenn_journal.py: each journal key's heard flag "
                        "(HOENN_21_JOURNAL_FLAGS + n). Saved in the player's file, so never edit or reuse a number.")
    flags = lock["flags"]

    line_ids, rumor_ids = list(hints["lines"]), list(hints["rumors"])
    line_heard = [None] * len(line_ids)
    rumor_heard = [None] * len(rumor_ids)
    calls = []          # (call ID, flag)
    rows, texts, seen = [], [], set()

    def claim(table, i, flag, what):
        if table[i] is not None and table[i] != flag:
            sys.exit(f"journal.json: {what} feeds both {table[i]} and {flag}")
        table[i] = flag

    for e in cfg["entries"]:
        key = e["key"]
        if not KEY_RE.match(key) or key in seen:
            sys.exit(f"journal.json: key {key!r} is not a unique [A-Z0-9_] name")
        seen.add(key)
        if e["page"] not in pages:
            sys.exit(f"journal.json: {key}: unknown page {e['page']!r}")
        for f in ("hint", "title"):
            if len(e[f]) > NAME_MAX:
                sys.exit(f"journal.json: {key}: {f} {e[f]!r} is longer than {NAME_MAX} characters")
        if key not in flags:
            used = set(flags.values())
            flags[key] = next(n for n in range(FLAG_BLOCK + 1) if n not in used)
        if flags[key] >= FLAG_BLOCK:
            sys.exit(f"journal.json: the heard-flag block ({FLAG_BLOCK}) is full")
        flag = "FLAG_HOENN_HEARD_" + key
        heard = e.get("heard", {})
        for r in heard.get("rumors", []):
            if r not in rumor_ids:
                sys.exit(f"journal.json: {key}: no hint rumor {r!r}")
            claim(rumor_heard, rumor_ids.index(r), flag, "rumor " + r)
            for i, lid in enumerate(line_ids):  # every line that tells this rumor
                if hints["lines"][lid].get("rumor") == r:
                    claim(line_heard, i, flag, "line " + lid)
        for lid in heard.get("lines", []):
            if lid not in line_ids:
                sys.exit(f"journal.json: {key}: no hint line {lid!r}")
            claim(line_heard, line_ids.index(lid), flag, "line " + lid)
        for c in heard.get("calls", []):
            if any(c == old for old, _ in calls):
                sys.exit(f"journal.json: {key}: call {c} already feeds another entry")
            calls.append((c, flag))
        name = "".join(p.title() for p in key.split("_"))
        labels = {}
        for f in ("hint", "title", "rumor", "found_text"):
            label = "HoennSeek_Text_Journal%s%s" % (name, "".join(p.title() for p in f.split("_")))
            text = e[f] if f in ("hint", "title") else wrap(e[f])
            texts.append((label, text))
            labels[f] = label
        when = when_c(e.get("when"), name, texts)
        rows.append("    { %s, %s, %s, %s, %s, %s, %s, %s, HOENN_JOURNAL_PAGE_%s }, // %s"
                    % (conds_c(e["found"]), conds_c(heard.get("if")), when, labels["hint"], labels["title"],
                       labels["rumor"], labels["found_text"], flag, e["page"].upper(), key))

    # constants
    hdr = ["// Generated by tools/hoenn/gen_hoenn_journal.py from data/hoenn/journal.json. Do not edit.",
           "// Hoenn & Seek 2.1-05: the SEEKER'S JOURNAL's heard flags (2.1's generated journal block, 0x%X flags;" % FLAG_BLOCK,
           "// numbers are kept in data/hoenn/journal_flags.json). Included by constants/hoenn_events_2_1.h.",
           "#ifndef GUARD_CONSTANTS_HOENN_JOURNAL_H", "#define GUARD_CONSTANTS_HOENN_JOURNAL_H", "",
           "#define HOENN_JOURNAL_FLAGS        HOENN_21_JOURNAL_FLAGS",
           "#define HOENN_JOURNAL_FLAGS_COUNT  0x%X" % FLAG_BLOCK, ""]
    for i, p in enumerate(pages):
        hdr.append("#define HOENN_JOURNAL_PAGE_%-6s %d" % (p.upper(), i))
    hdr += ["#define HOENN_JOURNAL_PAGE_COUNT  %d" % len(pages),
            "#define HOENN_JOURNAL_PAGE_TODAY  %d // 2.1-06: the TODAY page (the first tab; its id comes after the regions)" % len(pages),
            "#define HOENN_JOURNAL_ENTRIES     %d // 2.1-06b: all entries; the POKéGEAR page keeps their ids in a u8" % len(cfg["entries"]), ""]
    if len(cfg["entries"]) > 255:  # src/hoenn_journal_page.c lists entry ids as u8
        sys.exit("journal.json: at most 255 entries (the POKéGEAR page's ids are u8)")
    for e in cfg["entries"]:
        hdr.append("#define %-40s (HOENN_JOURNAL_FLAGS + 0x%02X)" % ("FLAG_HOENN_HEARD_" + e["key"], flags[e["key"]]))
    hdr += ["", "#endif // GUARD_CONSTANTS_HOENN_JOURNAL_H"]

    tab = ["// Generated by tools/hoenn/gen_hoenn_journal.py from data/hoenn/journal.json. Do not edit.",
           "// Included by src/hoenn_journal.c.", ""]
    tab += ["extern const u8 %s[];" % l for l, _ in texts]
    tab += ["", "static const u8 *const sJournalPageNames[] = {"]
    tab += ["    COMPOUND_STRING(\"%s\")," % p for p in cfg["pages"]]
    tab += ["};", "", "static const struct HoennJournalEntry sJournalEntries[] = {"] + rows + ["};", "",
            "static const struct HoennJournalCall sJournalCalls[] = {"]
    tab += ["    { %s, %s }," % c for c in calls] or ["    { 0, 0 },"]
    tab += ["};"]

    hh = ["// Generated by tools/hoenn/gen_hoenn_journal.py from data/hoenn/journal.json and",
          "// data/hoenn/npc_hints.json. Do not edit. Included by src/hoenn_hints.c: the",
          "// SEEKER'S JOURNAL heard flag each hint line sets when shown (0 = none), in the",
          "// order of sHintLines (a rumor's lines all set its entry's flag).", "",
          "static const u16 sHintLineHeard[] = {"]
    hh += ["    %s, // %s" % (f or "0", lid) for f, lid in zip(line_heard, line_ids)]
    hh += ["};"]

    inc = ["@ Generated by tools/hoenn/gen_hoenn_journal.py from data/hoenn/journal.json. Do not edit.",
           "@ Hoenn & Seek 2.1-05: the SEEKER'S JOURNAL's texts (src/hoenn_journal.c).", ""]
    for label, t in texts:
        inc += ["%s::" % label, '\t.string "%s$"' % t, ""]

    open(P("include/constants/hoenn_journal.h"), "w").write("\n".join(hdr) + "\n")
    open(P("src/data/hoenn_journal.h"), "w").write("\n".join(tab) + "\n")
    open(P("src/data/hoenn_journal_hints.h"), "w").write("\n".join(hh) + "\n")
    open(P("data/scripts/hoenn_journal_texts.inc"), "w").write("\n".join(inc) + "\n")
    lock["flags"] = dict(sorted(flags.items(), key=lambda kv: kv[1]))
    with open(lock_path, "w") as fh:
        json.dump(lock, fh, indent=2)
        fh.write("\n")
    counts = {p: sum(e["page"] == p for e in cfg["entries"]) for p in pages}
    print("%d journal entries (%s); %d hint lines, %d rumors, %d calls feed them; %d of %d heard flags used"
          % (len(cfg["entries"]), ", ".join("%s %d" % kv for kv in counts.items()),
             sum(f is not None for f in line_heard), sum(f is not None for f in rumor_heard),
             len(calls), len(flags), FLAG_BLOCK))


if __name__ == "__main__":
    main()

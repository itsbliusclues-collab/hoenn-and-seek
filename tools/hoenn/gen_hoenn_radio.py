#!/usr/bin/env python3
"""Hoenn & Seek 2.1-02: the radio segment table.

Reads data/hoenn/radio_segments.json (its _comment documents the format) and
writes src/data/hoenn_radio_segments.h, the table src/hoenn_radio.c plays in
front of each station's broadcast. Conditions are the hint engine's (this reuses
gen_hoenn_hints.py's cond_c). Deterministic: re-running changes nothing.
"""
import json, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_hoenn_hints import cond_c  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
P = lambda *a: os.path.join(ROOT, *a)
WIDTH = 30          # characters per radio line (220 px; the longest HnS radio lines are 31)
MAX_LINES = 8       # MAX_SEGMENT_LINES in src/hoenn_radio.c
KEY_RE = re.compile(r"^[A-Za-z0-9_]+$")
STATIONS = {
    "oak": "HOENN_RADIO_OAK", "pokedex": "HOENN_RADIO_POKEDEX", "music": "HOENN_RADIO_MUSIC",
    "lucky": "HOENN_RADIO_LUCKY", "buena": "HOENN_RADIO_BUENA", "unown": "HOENN_RADIO_UNOWN",
    "places": "HOENN_RADIO_PLACES", "sing": "HOENN_RADIO_SING", "rocket": "HOENN_RADIO_ROCKET",
    "hoenn_sound": "HOENN_RADIO_HOENN_SOUND",
}


def wrap(text):
    """A string or list of strings -> radio lines of at most WIDTH characters.
    Each string starts a new line; no one-word last line where it can be helped."""
    out = []
    for part in (text if isinstance(text, list) else [text]):
        lines, cur = [], ""
        for w in part.split():
            if len(w) > WIDTH:
                sys.exit(f"radio_segments.json: word longer than a radio line: {w}")
            if cur and len(cur) + 1 + len(w) > WIDTH:
                lines.append(cur)
                cur = w
            else:
                cur = f"{cur} {w}" if cur else w
        lines.append(cur)
        if len(lines) >= 2 and len(lines[-1].split()) == 1 and len(lines[-2].split()) >= 2:
            head, moved = lines[-2].rsplit(" ", 1)
            if len(moved) + 1 + len(lines[-1]) <= WIDTH:
                lines[-2], lines[-1] = head, f"{moved} {lines[-1]}"
        out += lines
    return out


def c_str(s):
    return '_("%s")' % s.replace('"', '\\"')


def main():
    data = json.load(open(P("data/hoenn/radio_segments.json")))
    texts, rows, natives, seen = [], [], [], set()
    for seg in data["segments"]:
        key = seg["key"]
        if not KEY_RE.match(key) or key in seen:
            sys.exit(f"radio_segments.json: bad or duplicate key {key!r}")
        seen.add(key)
        if seg["station"] not in STATIONS:
            sys.exit(f"radio_segments.json: {key}: unknown station {seg['station']!r}")
        conds = seg.get("if", [])
        cond_init = "NULL" if not conds else \
            "(const struct HoennHintCond[]){%s}" % ", ".join(cond_c(c) for c in conds)
        if ("native" in seg) == ("text" in seg):
            sys.exit(f"radio_segments.json: {key}: give exactly one of text / native")
        if "native" in seg:
            n, bufs = seg["lines"], seg.get("buffers", 0)
            lines_init, builder = "NULL", seg["native"]
            natives.append(builder)
        else:
            lines = wrap(seg["text"])
            n, bufs, builder = len(lines), 0, "NULL"
            for i, l in enumerate(lines):
                texts.append(f"static const u8 sRadioText_{key}_{i}[] = {c_str(l)};")
            texts.append(f"static const u8 *const sRadioLines_{key}[] = {{"
                         + ", ".join(f"sRadioText_{key}_{i}" for i in range(n)) + "};")
            lines_init = f"sRadioLines_{key}"
        if not 1 <= n <= MAX_LINES:
            sys.exit(f"radio_segments.json: {key}: {n} lines (1-{MAX_LINES})")
        heard = seg.get("heard", "0")
        if heard != "0" and not heard.startswith("FLAG_HOENN_HEARD_"):
            sys.exit(f"radio_segments.json: {key}: heard must be a FLAG_HOENN_HEARD_ flag")
        rows.append(f"    {{ // {key}\n        .station = {STATIONS[seg['station']]}, .maxLines = {n}, .buffers = {bufs},\n"
                    f"        .heard = {heard}, .conds = {cond_init}, "
                    f".condCount = {len(conds)},\n        .lines = {lines_init}, .builder = {builder},\n    }},")
    out = ["// Generated by tools/hoenn/gen_hoenn_radio.py from data/hoenn/radio_segments.json. Do not edit.",
           "// Included by src/hoenn_radio.c.", ""]
    out += texts + ([""] if texts else [])
    out += ["static const struct HoennRadioSegment sRadioSegments[] =", "{"] + rows + ["};", ""]
    path = P("src/data/hoenn_radio_segments.h")
    text = "\n".join(out)
    if not os.path.exists(path) or open(path).read() != text:
        open(path, "w").write(text)
    print(f"radio segments: {len(rows)} ({len(natives)} built at runtime)")


if __name__ == "__main__":
    main()

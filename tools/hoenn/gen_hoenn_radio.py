#!/usr/bin/env python3
"""Hoenn & Seek 2.1 (part 02): the radio's news segments.

Reads data/hoenn/radio_segments.json (its "_comment" explains the format) and
writes src/data/hoenn_radio_segments.h, the table src/hoenn_radio.c reads.

Each segment plays on one PokéGear station before that station's own broadcast
(in the intro of PROF.OAK's POKéMON TALK), when all its conditions hold. The
conditions are the hint engine's (gen_hoenn_hints.py, cond_c), so a segment and
a hint line say "after X, until Y" the same way.

Checks (the run stops with a message):
  - every segment has a unique "key" (letters, digits, _) and a known station;
  - it has either "lines" (1-3 fixed lines) or a "builder" (a C function in
    include/hoenn.h or hoenn_2_1.h with HoennRadioBuilder's signature), not both;
  - each fixed line fits the radio's text box: at most LINE_CHARS characters,
    the longest of HnS's own radio lines;
  - a "heard" flag is a FLAG_HOENN_ name.

Deterministic and idempotent; run by tools/hoenn/regen_all.sh. Re-run after
editing the JSON, then rebuild.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from gen_hoenn_hints import conds_c  # noqa: E402  (the same condition format)

SRC = os.path.join(ROOT, "data", "hoenn", "radio_segments.json")
OUT = os.path.join(ROOT, "src", "data", "hoenn_radio_segments.h")
KEY_RE = re.compile(r"^[A-Za-z0-9_]+$")
LINE_CHARS = 31   # "MARY: PROF.OAK's POKéMON TALK!" is HnS's longest line
MAX_LINES = 3

STATIONS = {  # JSON name -> HOENN_RADIO_* (include/hoenn_2_1.h)
    "oak_talk": "HOENN_RADIO_POKEMON_TALK",
    "pokedex_show": "HOENN_RADIO_POKEDEX_SHOW",
    "pokemon_music": "HOENN_RADIO_POKEMON_MUSIC",
    "lucky_channel": "HOENN_RADIO_LUCKY_CHANNEL",
    "buenas_password": "HOENN_RADIO_BUENAS_PASSWORD",
    "unown": "HOENN_RADIO_UNOWN",
    "places_and_people": "HOENN_RADIO_PLACES_AND_PEOPLE",
    "lets_all_sing": "HOENN_RADIO_LETS_ALL_SING",
    "poke_flute": "HOENN_RADIO_POKE_FLUTE",
    "rocket": "HOENN_RADIO_ROCKET",
    "hoenn_sound": "HOENN_RADIO_HOENN_SOUND",
}


def fail(msg):
    sys.exit(f"gen_hoenn_radio.py: {msg}")


def visible(text):
    """Characters as the radio box shows them (POKéMON's é is one)."""
    return len(text)


def c_string(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def main():
    with open(SRC, encoding="utf-8") as f:
        data = json.load(f)

    # 2.0's and part 02's rows, then each track's (they play in this order).
    segments = data["segments"] + data.get("track_a", []) + data.get("track_b", [])
    keys, out_lines, rows = set(), [], []
    for seg in segments:
        key = seg.get("key", "")
        if not KEY_RE.match(key) or key in keys:
            fail(f"segment key {key!r} is missing, not letters/digits/_, or used twice")
        keys.add(key)
        if seg.get("station") not in STATIONS:
            fail(f"{key}: unknown station {seg.get('station')!r} (one of {', '.join(sorted(STATIONS))})")
        lines, builder = seg.get("lines"), seg.get("builder")
        if bool(lines) == bool(builder):
            fail(f"{key}: give either \"lines\" or \"builder\", not both or neither")
        heard = seg.get("heard")
        if heard is not None and not heard.startswith("FLAG_HOENN_"):
            fail(f"{key}: \"heard\" must be a FLAG_HOENN_ flag, not {heard!r}")

        if lines:
            if not 1 <= len(lines) <= MAX_LINES:
                fail(f"{key}: 1-{MAX_LINES} lines, not {len(lines)}")
            names = []
            for i, line in enumerate(lines):
                if visible(line) > LINE_CHARS:
                    fail(f"{key}: line {i + 1} is {visible(line)} characters, the radio shows {LINE_CHARS}: {line!r}")
                name = f"sRadioSeg_{key}_{i}"
                out_lines.append(f'static const u8 {name}[] = _("{c_string(line)}");')
                names.append(name)
            out_lines.append(f"static const u8 *const sRadioSeg_{key}[] = {{ {', '.join(names)} }};")
            body = f"{len(lines)}, sRadioSeg_{key}, NULL"
        else:
            if not re.match(r"^Hoenn\w+$", builder):
                fail(f"{key}: builder {builder!r} should be a Hoenn* C function")
            body = f"0, NULL, {builder}"
        rows.append(f"    // {key}" + (f": {seg['note']}" if seg.get("note") else ""))
        rows.append(f"    {{ {STATIONS[seg['station']]}, {conds_c(seg.get('if', []))}, {body}, {heard or 0} }},")

    text = [
        "// Generated by tools/hoenn/gen_hoenn_radio.py from data/hoenn/radio_segments.json.",
        "// Do not edit: change the JSON and re-run the generator. Read by src/hoenn_radio.c.",
        "",
        *out_lines,
        "",
        "// station, conditions, fixed lines, builder, heard flag",
        "static const struct HoennRadioSegment sHoennRadioSegments[] =",
        "{",
        *rows,
        "};",
        "",
    ]
    new = "\n".join(text)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if new != old:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(new)
        print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(segments)} segments)")
    else:
        print(f"{os.path.relpath(OUT, ROOT)} unchanged ({len(segments)} segments)")


if __name__ == "__main__":
    main()

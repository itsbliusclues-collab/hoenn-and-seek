#!/usr/bin/env python3
"""Hoenn & Seek 2.1-07: the daily swarm table.

Reads data/hoenn/swarms.json (its comment explains the format) and writes
src/data/hoenn_swarms.h, the table src/hoenn_swarm.c rolls from. A row's level
range defaults to the map's own land table: HnS's tables in
src/data/wild_encounters.json for Johto/Kanto maps, the Hoenn tables in
data/hoenn/wild_encounters_hoenn.json for Hoenn ones (the first table with land
encounters, which is the day table where a map has two). Fails if a map has
no land table. Deterministic; in regen_all.sh.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
def P(*a): return os.path.join(ROOT, *a)


def land_tables():
    """MAP_ id -> (min, max) of its first land table, HnS tables then Hoenn ones."""
    out = {}
    d = json.load(open(P("src/data/wild_encounters.json")))
    tabs = [e for g in d["wild_encounter_groups"] if g.get("label") == "gWildMonHeaders"
            for e in g["encounters"] if "_hns" in e["base_label"] and "Unused" not in e["base_label"]]
    tabs += json.load(open(P("data/hoenn/wild_encounters_hoenn.json")))["encounters"]
    for e in tabs:
        lm = e.get("land_mons")
        if lm and e["map"] not in out:
            out[e["map"]] = (min(m["min_level"] for m in lm["mons"]), max(m["max_level"] for m in lm["mons"]))
    return out


def main():
    cfg = json.load(open(P("data/hoenn/swarms.json")))
    land = land_tables()
    rows = []
    for i, s in enumerate(cfg["swarms"]):
        mj = P("data/maps", s["map"], "map.json")
        if not os.path.exists(mj):
            sys.exit("swarms.json: no map %s" % s["map"])
        mid = json.load(open(mj))["id"]
        if mid not in land:
            sys.exit("swarms.json: %s has no land table" % s["map"])
        lo, hi = s.get("levels", land[mid])
        if not (1 <= lo <= hi <= 100) or not (1 <= s["rate"] <= 100):
            sys.exit("swarms.json: %s: bad levels or rate" % s["map"])
        rows.append("    { MAP_GROUP(%s), MAP_NUM(%s), SPECIES_%s, %d, %d, %d }, // %d: %s"
                    % (mid, mid, s["species"], lo, hi, s["rate"], i, s.get("note", "")))
    out = ["// Generated by tools/hoenn/gen_hoenn_swarms.py from data/hoenn/swarms.json. Do not edit.",
           "// Included by src/hoenn_swarm.c: {map group, map num, species, min level, max level, rate %}.", "",
           "static const struct HoennSwarm sHoennSwarms[] = {"] + rows + ["};"]
    open(P("src/data/hoenn_swarms.h"), "w").write("\n".join(out) + "\n")
    print("%d swarms" % len(rows))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Hoenn & Seek 2.1-21 to 23: fan-favorite chains (Brock, Misty, Blue).

Reads data/hoenn/fan_chains.json (its comment explains the format) and writes:
  - src/data/hoenn_fan_chains.h: the chain table src/hoenn_fan_chains.c reads
    (where each step happens, the vars, each chain's pool of lines);
  - data/scripts/hoenn_fan_chains.inc: the pool texts (word-wrapped like the hint
    lines), included from data/scripts/hoenn_2_1_lane_b.inc.
The chains' scenes are hand-written scripts in hoenn_2_1_lane_b.inc, and their
objects are placed by hand in map.json; only the tables are generated.
Deterministic; regen_all.sh runs it. Re-run after editing the JSON, then rebuild.
"""
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_hoenn_hints import wrap, conds_c  # same wrapping and conditions as the hint lines

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
P = lambda *a: os.path.join(ROOT, *a)
STEPS = 4      # HOENN_CHAIN_DONE (constants/hoenn_events_2_1.h)
POOL_MAX = 32  # HoennSeek_ChainPoolLine's buffer of holding lines


def main():
    spec = json.load(open(P("data/hoenn/fan_chains.json")))
    weekends = {l["key"] for l in json.load(open(P("data/hoenn/leader_weekends.json")))["leaders"]}
    head = ["// Generated by tools/hoenn/gen_hoenn_chains.py from data/hoenn/fan_chains.json. Do not edit.", ""]
    inc = ["@ Generated by tools/hoenn/gen_hoenn_chains.py from data/hoenn/fan_chains.json. Do not edit.",
           "@ The fan chains' pool lines (src/hoenn_fan_chains.c).", ""]
    tables, rows = [], []
    for c in spec["chains"]:
        k = c["key"]
        if c["leader"] not in weekends:
            sys.exit(f"{k}: leader {c['leader']} has no weekend in leader_weekends.json")
        if len(c["steps"]) != STEPS:
            sys.exit(f"{k}: a chain has {STEPS} steps")
        if not 0 < len(c["pool"]) <= POOL_MAX:
            sys.exit(f"{k}: the pool needs 1-{POOL_MAX} lines")
        lines = []
        for n, line in enumerate(c["pool"]):
            label = "HoennSeek_Text_ChainPool_%s_%d" % (k, n)
            head.append("extern const u8 %s[];" % label)
            inc += ["%s::" % label, '\t.string "%s$"' % wrap(line["text"]), ""]
            lines.append("    {%s, %s}," % (conds_c(line.get("if", [])), label))
        tables += ["static const struct HoennChainLine sChainPool_%s[] = {" % k] + lines + ["};", ""]
        places = ", ".join("0" if s == "spot" else s for s in c["steps"])
        rows.append("    [%s] = {FLAG_HOENN_WEEKEND_SPOT_%s, %s, %s, {%s}, sChainPool_%s, ARRAY_COUNT(sChainPool_%s)},"
                    % (c["id"], c["leader"], c["stage_var"], c["weekend_var"], places, k, k))
    head += [""] + tables + ["static const struct HoennFanChain sFanChains[] = {"] + rows + ["};", ""]
    open(P("src/data/hoenn_fan_chains.h"), "w").write("\n".join(head))
    open(P("data/scripts/hoenn_fan_chains.inc"), "w").write("\n".join(inc))
    print("fan chains: %d, pool lines: %d" % (len(spec["chains"]), sum(len(c["pool"]) for c in spec["chains"])))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Hoenn & Seek 2.1-03: the screen checker.

For every map in the HnS build, slides the game's object window over every
tile the player can stand on and counts what can be loaded at once:

  objects   map objects alive at once. The engine has 16 object event slots
            (OBJECT_EVENTS_COUNT); the player, the follower and one scripted
            object (a camera, a scene's extra) take three, so a map may use 13.
  palettes  distinct sprite palettes those objects need. The GBA has 16 OBJ
            palette slots. Measured in the emulator (2.1-03, see RESERVED):
            weather, the player, the player's reflection or surf blob, the
            follower, the town light and two field-effect palettes take up to
            seven, so a map's objects may use 9. NPCs share a handful of
            palettes (OBJ_EVENT_PAL_TAG_NPC_1, ...); every Pokémon object
            brings its own (its species, plus its shiny / female variants), so
            Pokémon are what fills this budget.

The window is the engine's own: an object spawns while it is inside
x in [player - 9, player + 10], y in [player - 7, player + 9]
(TrySpawnObjectEvents / RemoveObjectEventsOutsideView, src/event_object_movement.c),
widened by a wandering object's movement range.

What can't be on screen together counts once:
  - objects hidden by FLAG_DAY_POKEMON vs FLAG_NIGHT_POKEMON: the worse of day
    and night is reported;
  - objects on the same tile (weekday guardians, lead bull breeds, swapped
    scene objects): one at a time, and its palette only counts if none of its
    variants' palettes is already on screen.
Anything else with a flag is assumed visible (the worst case).

Not counted: reflections of map objects in water (each reflected object needs
its palette + 0x2000; keep two palettes spare on screens by reflective water),
objects that scripts add at runtime from templates outside the map, and
neighbouring maps' objects (the engine only spawns the current map's).

Over budget today is recorded in data/hoenn/screen_baseline.json (generated by
--update-baseline). The check fails when a map goes over budget and is not in
the baseline, or gets worse than its baseline. So 2.0's existing screens stay
as they are, and every new placement has to fit.

Usage:
  check_screens.py                      check every map, print the over-budget ones
  check_screens.py MAP...               only these maps (folder names)
  check_screens.py --report FILE        also write the markdown report
  check_screens.py --update-baseline    record today's over-budget maps
  check_screens.py --quiet              print only failures (for generators)
Exit status 1 when a check fails.
"""
import json, os, re, struct, sys

import numpy as np

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
P = lambda *a: os.path.join(ROOT, *a)

OBJECT_SLOTS, PALETTE_SLOTS = 16, 16
# Slots the map's objects can't use (measured in the emulator, 2.1-03): player,
# follower, one scripted object.
RESERVED_OBJECTS = 3
# Palettes in use without any map object: PALTAG_WEATHER, the player, the
# player's reflection or surf blob, the follower, OBJ_EVENT_PAL_TAG_LIGHT
# (towns), FLDEFF_PAL_TAG_GENERAL_0/1. Seen together at Violet City at night.
RESERVED_PALETTES = 7
OBJECT_BUDGET = OBJECT_SLOTS - RESERVED_OBJECTS      # 13
PALETTE_BUDGET = PALETTE_SLOTS - RESERVED_PALETTES   # 9

# The engine's window around the player (see the header).
WIN_LEFT, WIN_RIGHT, WIN_UP, WIN_DOWN = 9, 10, 7, 9

DAY_FLAG, NIGHT_FLAG = "FLAG_DAY_POKEMON", "FLAG_NIGHT_POKEMON"
BASELINE = P("data/hoenn/screen_baseline.json")


# ---------------------------------------------------------------- inputs

def palette_tags():
    """OBJ_EVENT_GFX_* -> its palette tag name (shared NPC palettes)."""
    infos = {}
    for m in re.finditer(r"const struct ObjectEventGraphicsInfo (gObjectEventGraphicsInfo_\w+) = \{(.*?)\};",
                         open(P("src/data/object_events/object_event_graphics_info.h")).read(), re.S):
        t = re.search(r"\.paletteTag = (\w+)", m.group(2))
        infos[m.group(1)] = t.group(1) if t else None
    tags = {}
    for m in re.finditer(r"\[(OBJ_EVENT_GFX_\w+)\]\s*=\s*&(gObjectEventGraphicsInfo_\w+)",
                         open(P("src/data/object_events/object_event_graphics_info_pointers.h")).read()):
        tags[m.group(1)] = infos.get(m.group(2))
    return tags


GFX_TAGS = palette_tags()


def palette_of(gfx):
    """The palette an object's graphics need, as a comparable key."""
    g = gfx.replace(" ", "")
    m = re.match(r"OBJ_EVENT_GFX_MON_BASE\+SPECIES_(\w+?)((?:\+OBJ_EVENT_MON_\w+)*)$", g) \
        or re.match(r"OBJ_EVENT_GFX_SPECIES(?:_(SHINY|FEMALE|SHINY_FEMALE))?\((\w+)\)$", g)
    if m:
        if g.startswith("OBJ_EVENT_GFX_MON_BASE"):
            species, extra = m.group(1), m.group(2)
        else:
            species, extra = m.group(2), m.group(1) or ""
        if species.startswith("UNOWN"):
            species, extra = "UNOWN", extra.replace("FEMALE", "")  # one palette for every form (27b)
        if species == "NONE":
            species = "KANGASKHAN"  # lane B's Kangaskhan baby (30a)
        return "MON:" + species + ("+S" if "SHINY" in extra else "") + ("+F" if "FEMALE" in extra else "")
    tag = GFX_TAGS.get(g)
    if tag in (None, "TAG_NONE", "OBJ_EVENT_PAL_TAG_DYNAMIC"):
        return "GFX:" + g  # its own palette
    return tag


def hns_maps():
    """(folder, map.json) for every map compiled into the HnS build."""
    kept = set(json.load(open(P("data/hoenn/maps.json")))["items"])
    out = []
    for folder in sorted(os.listdir(P("data/maps"))):
        path = P("data/maps", folder, "map.json")
        if not os.path.exists(path):
            continue
        m = json.load(open(path))
        if m.get("game_version") == "hns" or (m.get("game_version") == "emerald" and folder in kept):
            out.append((folder, m))
    return out


LAYOUTS = {l["id"]: l for l in json.load(open(P("data/layouts/layouts.json")))["layouts"] if "id" in l}


def standable(layout_id):
    """Bool array [h][w]: tiles with no collision (where the player can be)."""
    l = LAYOUTS[layout_id]
    w, h = l["width"], l["height"]
    d = struct.unpack("<%dH" % (w * h), open(P(l["blockdata_filepath"]), "rb").read()[: w * h * 2])
    a = np.array(d, dtype=np.uint16).reshape(h, w)
    return ((a >> 10) & 3) == 0


# ---------------------------------------------------------------- counting

def coverage(h, w, obj):
    """Bool array [h][w]: player tiles from which `obj` can be alive."""
    x, y = int(obj["x"]), int(obj["y"])
    rx, ry = int(obj.get("movement_range_x", 0) or 0), int(obj.get("movement_range_y", 0) or 0)
    if not obj.get("movement_type", "").startswith(("MOVEMENT_TYPE_WANDER", "MOVEMENT_TYPE_WALK")):
        rx = ry = 0
    c = np.zeros((h, w), dtype=bool)
    x0, x1 = max(0, x - rx - WIN_RIGHT), min(w - 1, x + rx + WIN_LEFT)
    y0, y1 = max(0, y - ry - WIN_DOWN), min(h - 1, y + ry + WIN_UP)
    if x0 <= x1 and y0 <= y1:
        c[y0:y1 + 1, x0:x1 + 1] = True
    return c


def count_map(m, scenario):
    """(objects, palettes, (x, y) of the worst tile) for one scenario ('day' / 'night')."""
    can = standable(m["layout"])
    h, w = can.shape
    hidden = NIGHT_FLAG if scenario == "night" else DAY_FLAG
    objs = []
    for o in m.get("object_events", []):
        if o.get("type") == "clone" or "graphics_id" not in o:
            continue
        if o.get("flag") == hidden:
            continue
        objs.append(o)
    groups = {}
    for o in objs:
        groups.setdefault((int(o["x"]), int(o["y"])), []).append(o)

    objects = np.zeros((h, w), dtype=np.int32)
    tag_cover = {}   # palette -> where a single (ungrouped) object needs it
    multi = []       # (coverage, palettes) of tiles shared by several objects
    for tile, members in groups.items():
        cov = coverage(h, w, max(members, key=lambda o: int(o.get("movement_range_x", 0) or 0)))
        objects += cov
        tags = {palette_of(o["graphics_id"]) for o in members}
        if len(members) == 1:
            t = tags.pop()
            tag_cover[t] = tag_cover.get(t, np.zeros((h, w), dtype=bool)) | cov
        else:
            multi.append((cov, tags))
    palettes = np.zeros((h, w), dtype=np.int32)
    for cov in tag_cover.values():
        palettes += cov
    for cov, tags in multi:
        shared = np.zeros((h, w), dtype=bool)
        for t in tags:
            if t in tag_cover:
                shared |= tag_cover[t]
        palettes += cov & ~shared

    objects[~can] = 0
    palettes[~can] = 0
    if not can.any():
        return 0, 0, None
    worst = np.unravel_index(np.argmax(objects * 100 + palettes), objects.shape)
    return int(objects.max()), int(palettes.max()), (int(worst[1]), int(worst[0]))


def check(only=None):
    rows = {}
    for folder, m in hns_maps():
        if only and folder not in only:
            continue
        if m["layout"] not in LAYOUTS or not m.get("object_events"):
            continue
        res = [count_map(m, s) for s in ("day", "night")]
        o = max(r[0] for r in res)
        p = max(r[1] for r in res)
        at = max(res, key=lambda r: (r[0], r[1]))[2]
        rows[folder] = (o, p, at)
    return rows


# ---------------------------------------------------------------- output

def over(o, p):
    return o > OBJECT_BUDGET or p > PALETTE_BUDGET


def failures(rows, baseline):
    bad = []
    for folder, (o, p, at) in sorted(rows.items()):
        if not over(o, p):
            continue
        b = baseline.get(folder)
        if b is None:
            bad.append(f"{folder}: {o} objects / {p} palettes near {at} (budget {OBJECT_BUDGET} / {PALETTE_BUDGET})")
        elif o > max(b[0], OBJECT_BUDGET) or p > max(b[1], PALETTE_BUDGET):
            bad.append(f"{folder}: {o} objects / {p} palettes near {at}, worse than its baseline {b[0]} / {b[1]}")
    return bad


def report(rows, baseline, path):
    lines = ["# Screen check", "",
             "Generated by `tools/hoenn/check_screens.py --report` (2.1-03; its header explains the counting).",
             f"Budgets per screen: **{OBJECT_BUDGET} map objects** (16 slots − player, follower, one scripted object) "
             f"and **{PALETTE_BUDGET} sprite palettes** for them (16 − {RESERVED_PALETTES} measured in the emulator).",
             f"Maps checked: {len(rows)}. Over budget: {sum(1 for r in rows.values() if over(r[0], r[1]))} "
             f"(all recorded in `data/hoenn/screen_baseline.json`, so only new crowding fails the check).", "",
             "## Over budget (worst screen per map)", "",
             "| Map | Objects | Palettes | Worst tile |", "|---|---|---|---|"]
    for folder, (o, p, at) in sorted(rows.items(), key=lambda kv: (-max(kv[1][0] - OBJECT_BUDGET, kv[1][1] - PALETTE_BUDGET), kv[0])):
        if over(o, p):
            lines.append(f"| {folder} | {o}{' ⚠' if o > OBJECT_BUDGET else ''} | {p}{' ⚠' if p > PALETTE_BUDGET else ''} | {at} |")
    lines += ["", "## Busiest screens within budget (top 20)", "",
              "| Map | Objects | Palettes | Worst tile |", "|---|---|---|---|"]
    ok = sorted(((f, r) for f, r in rows.items() if not over(r[0], r[1])), key=lambda kv: (-kv[1][1], -kv[1][0], kv[0]))
    for folder, (o, p, at) in ok[:20]:
        lines.append(f"| {folder} | {o} | {p} | {at} |")
    text = "\n".join(lines) + "\n"
    if not os.path.exists(path) or open(path).read() != text:
        open(path, "w").write(text)


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    quiet = "--quiet" in argv
    update = "--update-baseline" in argv
    rep = None
    if "--report" in argv:
        rep = argv[argv.index("--report") + 1]
        argv.remove(rep)
    only = {a for a in argv if not a.startswith("--")} or None
    rows = check(only)
    baseline = json.load(open(BASELINE))["maps"] if os.path.exists(BASELINE) else {}
    if update and only:
        print("check_screens: --update-baseline needs every map (no map names)", file=sys.stderr)
        return 1
    if update:
        data = {"_comment": ["Generated by tools/hoenn/check_screens.py --update-baseline (2.1-03).",
                             "Maps already over the screen budget when the checker was added: [objects, palettes].",
                             "The check only fails if one of these gets worse, or another map goes over."],
                "maps": {f: [o, p] for f, (o, p, _) in sorted(rows.items()) if over(o, p)}}
        text = json.dumps(data, indent=1) + "\n"
        if not os.path.exists(BASELINE) or open(BASELINE).read() != text:
            open(BASELINE, "w").write(text)
        baseline = data["maps"]
    if rep:
        report(rows, baseline, rep)
    bad = failures(rows, baseline)
    if not quiet:
        n = sum(1 for r in rows.values() if over(r[0], r[1]))
        print(f"screens: {len(rows)} maps, {n} over budget (baselined), {len(bad)} failing")
    for b in bad:
        print("check_screens: " + b, file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())

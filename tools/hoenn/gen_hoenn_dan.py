#!/usr/bin/env python3
"""Hoenn & Seek 2.1-31: DAN's episodes.

Reads data/hoenn/dan_episodes.json (its _comment documents the format) and writes
  data/scripts/hoenn_dan_texts.inc  the message texts (word-wrapped like the hint
                                    lines, so tools/hoenn/text_audit.py measures them)
  src/data/hoenn_dan.h              the episode table src/hoenn_dan.c reads
Deterministic: re-running changes nothing.
"""
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_hoenn_hints import wrap  # noqa: E402
import gen_hoenn_radio  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
P = lambda *a: os.path.join(ROOT, *a)
MAX_PARTS = 4        # HOENN_DAN_MAX_PARTS in src/hoenn_dan.c
MAX_RADIO = 4        # HOENN_DAN_MAX_RADIO
MAX_TITLE = 18


def fail(msg):
    sys.exit("dan_episodes.json: " + msg)


def main():
    data = json.load(open(P("data/hoenn/dan_episodes.json"), encoding="utf-8"))
    inc = ["@ Generated by tools/hoenn/gen_hoenn_dan.py from data/hoenn/dan_episodes.json.",
           "@ Do not edit: change the JSON and re-run (tools/hoenn/regen_all.sh does).", ""]
    h = ["// Generated by tools/hoenn/gen_hoenn_dan.py from data/hoenn/dan_episodes.json.",
         "// Do not edit: change the JSON and re-run (tools/hoenn/regen_all.sh does).", ""]
    externs, body, rows = [], [], []

    def text(label, boxes):
        inc.extend([label + "::", '\t.string "%s$"' % wrap(boxes), ""])
        externs.append("extern const u8 %s[];" % label)
        return label

    eps = data["episodes"]
    if not eps:
        fail("no episodes")
    for i, ep in enumerate(eps):
        title = ep["title"]
        if len(title) > MAX_TITLE:
            fail(f"episode {i}: title longer than {MAX_TITLE}: {title}")
        parts = ep["parts"]
        if not 1 <= len(parts) <= MAX_PARTS:
            fail(f"episode {i}: 1..{MAX_PARTS} parts")
        part_labels = [text(f"HoennSeek_Text_Dan_E{i}_P{k}", p) for k, p in enumerate(parts)]
        teaser = text(f"HoennSeek_Text_Dan_E{i}_Teaser", ep["teaser"]) if ep["teaser"] else "NULL"
        radio = gen_hoenn_radio.wrap(ep["radio"])
        if len(radio) > MAX_RADIO:
            fail(f"episode {i}: radio text wraps to {len(radio)} lines (at most {MAX_RADIO})")
        body.append(f"static const u8 sDanTitle_{i}[] = {gen_hoenn_radio.c_str(title)};")
        for k, line in enumerate(radio):
            body.append(f"static const u8 sDanRadio_{i}_{k}[] = {gen_hoenn_radio.c_str(line)};")
        rows.append("    {\n"
                    f"        .title = sDanTitle_{i},\n"
                    f"        .parts = {{{', '.join(part_labels)}}},\n"
                    f"        .numParts = {len(parts)},\n"
                    f"        .teaser = {teaser},\n"
                    f"        .radio = {{{', '.join(f'sDanRadio_{i}_{k}' for k in range(len(radio)))}}},\n"
                    f"        .numRadio = {len(radio)},\n"
                    "    },")
    text("HoennSeek_Text_Dan_Outro", data["outro"])
    for key, boxes in data["lines"].items():
        if not key.startswith("_"):
            text(f"HoennSeek_Text_Dan_{key}", boxes)

    h += externs + [""] + body + ["", "static const struct HoennDanEpisode sDanEpisodes[] =", "{"] \
        + rows + ["};", ""]
    with open(P("data/scripts/hoenn_dan_texts.inc"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(inc))
    with open(P("src/data/hoenn_dan.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(h))
    print(f"gen_hoenn_dan: {len(eps)} episodes, {sum(len(e['parts']) for e in eps)} installments")


if __name__ == "__main__":
    main()
